# Generates demo/holo_element/ssr/index.html: a Tier-2 element rendered on the
# SERVER as a declarative shadow root (Noizu.Tessera.Hologram.Render), which
# the stock runtime then hydrates (TESSER SSR-1/SSR-2).
#
#     cd demo/hologram_app && mix run --no-start priv/gen_ssr_page.exs
#
# (--no-start: renders without booting the demo endpoint, so it also runs
# while `mix holo` holds :5586.)
alias Noizu.Tessera.Hologram.Render

counter =
  Render.element(
    HoloKit.Components.Counter,
    "tsr-holo-counter",
    %{label: "server pings", step: 2},
    attrs: %{"id" => "ssr-counter", "data-cy" => "ssr-counter"}
  )

page = """
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>tessera tier 2 — SSR / declarative shadow DOM</title>
</head>
<body>
  <h1 data-cy="ssr-title">SSR (declarative shadow DOM) host — tier 2</h1>
  <!-- generated by demo/hologram_app/priv/gen_ssr_page.exs — do not edit -->
  #{counter}
  <p>count-changed heard: <strong data-cy="ssr-count-value">0</strong></p>
  <script>
    // Snapshot the SERVER nodes before the runtime loads, so the spec can
    // prove hydration kept them (identity) rather than replacing them.
    const root = document.getElementById("ssr-counter").shadowRoot;
    window.__ssrServerNodes = {
      host: root && root.querySelector("[data-tessera-holo-host]"),
      count: root && root.querySelector('[data-cy="holo-counter-count"]'),
      inc: root && root.querySelector('[data-cy="holo-counter-inc"]'),
    };
    document.addEventListener("count-changed", (e) => {
      document.querySelector('[data-cy="ssr-count-value"]').textContent = String(e.detail.count);
    });
  </script>
  <script src="../dist/tessera-holo/tessera-runtime.umd.js"></script>
  <script src="../dist/tessera-holo/counter.umd.js"></script>
  <script>
    window.TesseraHoloBundle.defineElement("tsr-holo-counter", "HoloKit.Components.Counter");
  </script>
</body>
</html>
"""

out = Path.expand("../holo_element/ssr/index.html", File.cwd!())
File.write!(out, page)
IO.puts("gen_ssr_page: wrote #{Path.relative_to_cwd(out)}")
