defmodule Noizu.Tessera.Gallery do
  @moduledoc false

  # Content builders behind `mix tessera.gen.gallery`. Pure functions of
  # their arguments (the Mix task only resolves the package + paths and
  # writes files) so they are unit-testable without a Mix project context.
  #
  # The generated gallery is FRAMEWORK-AGNOSTIC: a static index.html plus an
  # esbuild entry that imports the package's component `.mjs` modules (their
  # load-bearing top-level register() defines the elements) and the tessera
  # gallery runtime (`priv/gallery/gallery.mjs`). The runtime reads the
  # package's Custom Elements Manifest and renders live demos, typed
  # attr/prop editors, slot-content editors and an event log per component.

  @default_out "gallery"

  @doc """
  Builds all gallery file contents for `package_mod` under project `root`.
  Returns a list of `{absolute_path, content}` — the caller writes them.

  Options:

    * `:out` — output directory relative to `root` (default `"gallery"`);
    * `:tessera_root` — path to the tessera library checkout (required; the
      runtime + `@noizu/tessera-core` are referenced from it);
    * `:app` — app name for the generated package.json (default: the
      package module underscored).
  """
  @spec generate(module(), String.t(), keyword()) :: [{String.t(), String.t()}]
  def generate(package_mod, root, opts \\ []) do
    out_dir = Path.join(root, opts[:out] || @default_out)
    src_dir = Path.join(out_dir, "src")

    tessera_root =
      case opts[:tessera_root] do
        nil -> raise ArgumentError, "tessera gallery: :tessera_root option is required"
        path -> Path.expand(path, root)
      end

    app = opts[:app] || package_mod |> Macro.underscore() |> String.replace("/", "_")
    title = inspect(package_mod)

    specs = Enum.map(package_mod.components(), & &1.__tessera_spec__())

    Enum.each(specs, fn spec ->
      unless spec.js do
        raise ArgumentError,
              "tessera gallery: #{inspect(spec.module)} declares no :js option — " <>
                "the gallery needs the colocated .mjs element"
      end
    end)

    import_paths =
      Enum.map(specs, fn spec ->
        mjs = Path.expand(spec.js, Path.dirname(Path.expand(spec.file, root)))
        Path.relative_to(mjs, src_dir, force: true)
      end)

    runtime =
      Path.relative_to(Path.join([tessera_root, "priv", "gallery", "gallery.mjs"]), src_dir,
        force: true
      )

    chrome =
      Path.relative_to(Path.join([tessera_root, "priv", "gallery", "gallery.css"]), src_dir,
        force: true
      )

    core = Path.relative_to(Path.join(tessera_root, "priv/js"), out_dir, force: true)

    [
      {Path.join(out_dir, "index.html"), index_html(title)},
      {Path.join(src_dir, "main.mjs"), main_mjs(title, runtime, chrome, import_paths)},
      {Path.join(out_dir, "custom-elements.json"),
       Jason.encode!(package_mod.cem(), pretty: true) <> "\n"},
      {Path.join(out_dir, "package.json"), package_json(app, title, core)},
      {Path.join(out_dir, "serve.mjs"), serve_mjs()},
      {Path.join(out_dir, ".gitignore"), "node_modules/\ndist/\n"}
    ]
  end

  @doc "The generated static gallery page."
  @spec index_html(String.t()) :: String.t()
  def index_html(title) do
    """
    <!DOCTYPE html>
    <html lang="en">
      <head>
        <meta charset="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <title>#{title} — tessera gallery</title>
        <link rel="stylesheet" href="./dist/bundle.css" />
        <script type="module" src="./dist/bundle.js"></script>
      </head>
      <body>
        <div class="tsr-gallery-page">
          <header>
            <h1 data-cy="gallery-title">#{title} — component gallery</h1>
            <p>
              Live demos, typed attribute/property editors, slot content and an
              event log — driven by <code>custom-elements.json</code>. Generated
              by <code>mix tessera.gen.gallery</code>.
            </p>
          </header>
          <main id="gallery" data-cy="gallery"></main>
        </div>
      </body>
    </html>
    """
  end

  @doc "The generated esbuild entry: component imports + gallery runtime."
  @spec main_mjs(String.t(), String.t(), String.t(), [String.t()]) :: String.t()
  def main_mjs(title, runtime_rel, chrome_rel, import_paths) do
    imports = Enum.map_join(import_paths, "\n", fn path -> "import #{inspect(path)};" end)

    """
    // Generated by `mix tessera.gen.gallery` for #{title} — do not edit by
    // hand; regenerate with that task after changing the package's components.
    //
    // Importing the component modules is ALL the setup they need: each .mjs
    // has a load-bearing top-level register() call (CONTRACT.md §3). esbuild
    // bundles these imports plus the tessera gallery runtime into
    // dist/bundle.js (and the gallery chrome into dist/bundle.css).
    import { mountGallery } from #{inspect(runtime_rel)};
    import #{inspect(chrome_rel)};
    #{imports}

    mountGallery({ cemUrl: "./custom-elements.json" });
    """
  end

  @doc "The generated gallery package.json (esbuild build + static serve)."
  @spec package_json(String.t(), String.t(), String.t()) :: String.t()
  def package_json(app, title, core_rel) do
    """
    {
      "name": "#{app}-gallery",
      "private": true,
      "type": "module",
      "description": "Interactive tessera component gallery for #{title} (generated by mix tessera.gen.gallery).",
      "scripts": {
        "build": "esbuild src/main.mjs --bundle --format=esm --outfile=dist/bundle.js --log-level=info",
        "serve": "node serve.mjs"
      },
      "dependencies": {
        "@noizu/tessera-core": "file:#{core_rel}",
        "lit": "^3.3.3"
      },
      "devDependencies": {
        "esbuild": "^0.25.0"
      }
    }
    """
  end

  @doc """
  The generated static file server (no dependencies — `node serve.mjs`).
  Serves the gallery directory on http://localhost:5588 (PORT overridable).
  """
  @spec serve_mjs() :: String.t()
  def serve_mjs do
    """
    // Tiny static file server for the tessera gallery (no dependencies —
    // `node serve.mjs` is the whole tool). Serves this directory on
    // http://localhost:5588 with correct MIME types for .html/.js/.mjs/.json.
    import { createServer } from "node:http";
    import { readFile } from "node:fs/promises";
    import { extname, join, normalize } from "node:path";
    import { fileURLToPath } from "node:url";

    const root = fileURLToPath(new URL(".", import.meta.url));
    const port = Number(process.env.PORT || 5588);

    const types = {
      ".html": "text/html; charset=utf-8",
      ".js": "text/javascript; charset=utf-8",
      ".mjs": "text/javascript; charset=utf-8",
      ".json": "application/json; charset=utf-8",
      ".css": "text/css; charset=utf-8",
    };

    createServer(async (req, res) => {
      try {
        let path = normalize(decodeURIComponent(new URL(req.url, "http://x").pathname));
        if (path.endsWith("/")) path += "index.html";
        const file = join(root, path);
        if (!file.startsWith(root)) throw new Error("traversal");
        const body = await readFile(file);
        res.writeHead(200, {"content-type": types[extname(file)] || "application/octet-stream"});
        res.end(body);
      } catch {
        res.writeHead(404, {"content-type": "text/plain"});
        res.end("not found");
      }
    }).listen(port, "127.0.0.1", () => {
      console.log(`tessera gallery serving ${root} at http://localhost:${port}`);
    });
    """
  end
end
