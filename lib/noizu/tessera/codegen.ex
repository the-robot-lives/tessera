defmodule Noizu.Tessera.Codegen do
  @moduledoc """
  Code generators over a `Noizu.Tessera.Spec`:

    * `contract_module/1` — the exact `<snake_tag>.contract.generated.mjs`
      text of CONTRACT.md §2 (camelCase keys, deterministic key order),
      written next to the component's `.mjs` at compile time;
    * `cem/1` — a Custom Elements Manifest (schemaVersion `"1.0.0"`) as a
      JSON-encodable map with string keys. Determinism note: the CONTRACT
      module above goes through `Spec.json_literal/1`, which key-sorts maps
      explicitly; the CEM map is encoded by Jason, whose map key order is
      arbitrary but stable within an OTP build — the golden fixture pins
      whatever it produces here, so regenerate goldens rather than assuming
      an order when the CEM shape changes.

  Both are pure functions of the spec — the golden fixtures under
  `test/fixtures/` pin their exact output.
  """

  alias Noizu.Tessera.Component.Styles
  alias Noizu.Tessera.Naming
  alias Noizu.Tessera.Spec

  @cem_schema_version "1.0.0"

  @doc """
  The `<snake_tag>.contract.generated.mjs` text for a spec, per CONTRACT.md §2.
  """
  @spec contract_module(Spec.t()) :: String.t()
  def contract_module(%Spec{} = spec) do
    attrs =
      Enum.map(spec.attrs, fn a ->
        "{ name: #{Spec.json_literal(Naming.snake_to_kebab(a.name))}, " <>
          "key: #{Spec.json_literal(Naming.snake_to_camel(a.name))}, " <>
          "type: #{Spec.json_literal(Atom.to_string(a.type))}, " <>
          "required: #{!!a[:required]}, " <>
          "default: #{Spec.json_literal(a[:default])} }"
      end)

    props =
      Enum.map(spec.props, fn p ->
        "{ name: #{Spec.json_literal(Naming.snake_to_camel(p.name))}, " <>
          "type: #{Spec.json_literal(Atom.to_string(p.type))}" <>
          json_flag(p) <>
          ", default: #{Spec.json_literal(p[:default])} }"
      end)

    events =
      Enum.map(spec.events, fn e ->
        "{ name: #{Spec.json_literal(e.name)}, detail: #{detail_object(e[:detail])} }"
      end)

    slots =
      Enum.map(slot_names(spec), fn name -> Spec.json_literal(name) end)

    cy = if spec.cy, do: Spec.json_literal(spec.cy), else: "null"

    """
    // Generated by noizu_tessera — tessera wire contract v#{spec.version}. Do not edit.
    // Source of truth: #{contract_source(spec)}
    export default {
      version: #{spec.version},
      tag: #{Spec.json_literal(spec.tag)},
      attrs:  #{inline_list(attrs)},
      props:  #{inline_list(props)},
      events: #{inline_list(events)},
      slots:  #{inline_list(slots)},
      cy: #{cy},
    };
    """
  end

  @doc """
  Writes `contract_module/1` output to `dir/<snake_tag>.contract.generated.mjs`
  only when the file's content differs — avoids rebuild loops where writing
  the generated file would itself retrigger compilers/watchers.
  Returns `:written | :unchanged | {:error, reason}`.
  """
  @spec write_contract_module(Spec.t(), String.t()) :: :written | :unchanged | {:error, term()}
  def write_contract_module(%Spec{} = spec, dir) do
    path = contract_path(spec, dir)
    content = contract_module(spec)

    case File.read(path) do
      {:ok, ^content} ->
        :unchanged

      _ ->
        case File.mkdir_p(dir) do
          :ok ->
            case File.write(path, content) do
              :ok -> :written
              {:error, reason} -> {:error, reason}
            end

          {:error, reason} ->
            {:error, reason}
        end
    end
  end

  @doc "Path of the generated contract module for a spec, under `dir`."
  @spec contract_path(Spec.t(), String.t()) :: String.t()
  def contract_path(%Spec{} = spec, dir),
    do: Path.join(dir, snake_tag(spec) <> ".contract.generated.mjs")

  @doc "snake_case form of the tag (`persona-card` → `persona_card`)."
  @spec snake_tag(Spec.t()) :: String.t()
  def snake_tag(%Spec{} = spec), do: String.replace(spec.tag, "-", "_")

  @doc """
  A Custom Elements Manifest (schemaVersion #{@cem_schema_version}) covering
  `specs`, as a JSON-encodable map with string keys.

  Per component declaration: `tagName`, `attributes` (kebab name, type,
  required flag, JSON-literal default), `members` (camelCase property fields
  with type, `json` flag and JSON-literal default), `events` (name +
  camelCase detail schema), `slots`, `cssProperties` (name + default) and
  `cssParts` — the last two fed by the spec DSL's `css`/`part` declarations.
  """
  @spec cem([Spec.t()]) :: map()
  def cem(specs) when is_list(specs) do
    %{
      "schemaVersion" => @cem_schema_version,
      "modules" => Enum.map(specs, &cem_module/1)
    }
  end

  # -- internals -------------------------------------------------------------

  defp contract_source(%Spec{module: nil, file: nil}), do: "Noizu.Tessera.Spec"
  defp contract_source(%Spec{module: nil, file: file}), do: file
  defp contract_source(%Spec{module: mod}), do: inspect(mod)

  defp json_flag(%{json: true}), do: ", json: true"
  defp json_flag(_), do: ""

  defp detail_object(nil), do: "{}"

  defp detail_object(detail) when is_map(detail) do
    detail
    |> Map.keys()
    |> Enum.sort()
    |> Enum.map(fn key ->
      "#{Naming.snake_to_camel(key)}: #{Spec.json_literal(Atom.to_string(detail[key]))}"
    end)
    |> Enum.map_join(", ", & &1)
    |> then(&"{#{&1}}")
  end

  defp slot_names(%Spec{} = spec) do
    case spec.slots do
      [] -> ["default"]
      slots -> Enum.map(slots, & &1.name)
    end
  end

  defp inline_list([]), do: "[]"

  defp inline_list(entries), do: "[#{Enum.join(entries, ", ")}]"

  # Theming surface (EXTENSION-CONTRACT.md §7), unified from BOTH declaration
  # mechanisms: explicit `css`/`part` DSL entries (from-lit / gallery metadata,
  # declaration order first) plus the styles DSL's scanned author-CSS reads
  # and template parts. Explicit declarations win on a name collision — they
  # are the author's deliberate statement; scanned additions follow sorted by
  # name for byte determinism. Reads inside {:shared, …} modules are JS-side
  # and not scanned — declare those explicitly or in the component's own
  # styles block.
  defp cem_css_properties(%Spec{} = spec) do
    explicit =
      Enum.map(spec.css_properties, fn c ->
        base = %{"name" => c.name}
        if c[:default] != nil, do: Map.put(base, "default", c.default), else: base
      end)

    explicit_names = MapSet.new(spec.css_properties, & &1.name)

    scanned =
      if spec.tag do
        spec.styles
        |> Enum.filter(&(&1.kind == :css))
        |> Enum.flat_map(&Styles.custom_property_reads(&1.value, spec.tag))
        |> Enum.reject(&MapSet.member?(explicit_names, &1.name))
        |> Enum.uniq_by(& &1.name)
        |> Enum.sort_by(& &1.name)
        |> Enum.map(fn
          %{name: name, default: nil} -> %{"name" => name}
          %{name: name, default: default} -> %{"name" => name, "default" => default}
        end)
      else
        []
      end

    explicit ++ scanned
  end

  # The generated element exposes a `root` part on the host plus every part
  # declared in the template markup; explicit `part` DSL declarations come
  # first. Spec-only components (no template) have no generated DOM to claim
  # a root part for — their explicit declarations still stand.
  defp cem_css_parts(%Spec{} = spec) do
    explicit = Enum.map(spec.parts, &%{"name" => &1.name})
    explicit_names = MapSet.new(spec.parts, & &1.name)

    generated =
      case spec.template do
        nil -> []
        template -> ["root" | Styles.parts(template.raw)]
      end

    rest =
      generated
      |> Enum.reject(&MapSet.member?(explicit_names, &1))
      |> Enum.map(&%{"name" => &1})

    Enum.uniq_by(explicit ++ rest, & &1["name"])
  end

  defp cem_module(%Spec{} = spec) do
    path = if spec.js, do: spec.js, else: snake_tag(spec) <> ".ex"

    declarations = [
      %{
        "customElements" => false,
        "description" => "tessera component #{spec.tag} (spec: #{contract_source(spec)})",
        "kind" => "custom-element-definition",
        "name" => spec.tag,
        "tagName" => spec.tag,
        "attributes" =>
          Enum.map(spec.attrs, fn a ->
            base = %{
              "name" => Naming.snake_to_kebab(a.name),
              "type" => %{"text" => Atom.to_string(a.type)}
            }

            base =
              if a[:required], do: Map.put(base, "required", true), else: base

            if a[:default] != nil,
              do: Map.put(base, "default", Spec.json_literal(a[:default])),
              else: base
          end),
        "members" =>
          Enum.map(spec.props, fn p ->
            member = %{
              "kind" => "field",
              "name" => Naming.snake_to_camel(p.name),
              "type" => %{"text" => Atom.to_string(p.type)}
            }

            member = if p[:json], do: Map.put(member, "json", true), else: member

            if p[:default] != nil,
              do: Map.put(member, "default", Spec.json_literal(p[:default])),
              else: member
          end),
        "events" =>
          Enum.map(spec.events, fn e ->
            %{
              "name" => e.name,
              "type" => %{"text" => "CustomEvent"},
              "detail" =>
                e[:detail]
                |> Map.new(fn {k, t} ->
                  {Naming.snake_to_camel(k), %{"text" => Atom.to_string(t)}}
                end)
            }
          end),
        "slots" => Enum.map(slot_names(spec), fn name -> %{"name" => name} end),
        "cssProperties" => cem_css_properties(spec),
        "cssParts" => cem_css_parts(spec)
      }
    ]

    %{"kind" => "javascript-module", "path" => path, "declarations" => declarations}
  end
end
