defmodule Noizu.Tessera.Component.LitCodegen do
  @moduledoc """
  SPIKE (`spike/elixir-to-lit`): emits the Lit element module for a spec that
  declared `state` / `template ~TSR` / `action` (docs/notes/spike-elixir-to-lit.md
  §codegen).

  Output (colocated with the component's `.ex`):

    * `<tag>.element.generated.mjs` — a `LitElement` subclass mixed with
      `TesseraElement` (CONTRACT.md §4): reactive properties from state +
      attrs + props (with Lit property options — `attribute` rename/disable,
      `reflect`, typed converters incl. `Array` for `:list`), a `render()`
      built from the template, one method per action (running the JS
      translated at compile time), one method per declared lifecycle hook
      (`shouldUpdate`/`willUpdate`/`firstUpdated`/`updated`), `emit` routed
      through `@noizu/tessera-core`'s `emit` (so the `data-tsr-on` Hologram
      bridge keeps working), and an exported `register()`.
    * `<snake>.mjs` — the `:js` entry wrapper (`register();` top-level —
      load-bearing for Hologram page bundles, CONTRACT.md §5). Written only
      when it does not exist, so a hand-written element `.mjs` is never
      clobbered.

  Deterministic: same spec in, same bytes out (golden fixtures pin it).
  """

  alias Noizu.Tessera.Codegen
  alias Noizu.Tessera.Component.Styles
  alias Noizu.Tessera.Naming
  alias Noizu.Tessera.Spec

  @lifecycle_order [:should_update, :will_update, :first_updated, :updated]

  # -- element module ----------------------------------------------------------

  @doc "The `<tag>.element.generated.mjs` text for a template-bearing spec."
  @spec element_module(Spec.t()) :: String.t()
  def element_module(%Spec{derived_from: nil} = spec), do: fresh_element_module(spec)
  def element_module(%Spec{} = spec), do: derived_element_module(spec)

  defp fresh_element_module(%Spec{} = spec) do
    class = class_name(spec)
    tag = spec.tag
    snake = Codegen.snake_tag(spec)
    shared = shared_imports(spec)

    imports =
      [lit_import(spec)] ++
        directive_imports(spec) ++
        [
          ~s|import { defineOnce, TesseraElement, emit } from "@noizu/tessera-core";|,
          ~s|import contract from "./#{snake}.contract.generated.mjs";|
        ] ++
        Enum.map(shared, fn {binding, path} ->
          ~s|import { styles as #{binding} } from #{Spec.json_literal(path)};|
        end)

    """
    // Generated by noizu_tessera (spike/elixir-to-lit) — do not edit.
    // Source of truth: #{source_name(spec)}.
    // Template lexer: #{spec.template[:lexer]}; subset: see docs/notes/spike-elixir-to-lit.md.
    #{Enum.join(imports, "\n")}

    // nil-safe interpolation helper (renders nothing for null/undefined).
    const __t = (v) => (v == null ? undefined : v);

    // Tessera base styles — the fixed :host defaults every element inherits
    // (first entry of the composed static styles array).
    const baseStyles = css`
    :host {
      display: block;
      font-family: system-ui, -apple-system, sans-serif;
    }
    `;

    class #{class} extends TesseraElement(LitElement, contract, #{extension_descriptor(spec)}) {
      static properties = #{properties_object(spec)};

      static styles = #{styles_array(spec, shared)};

      constructor() {
        super();
    #{constructor_defaults(spec)}
      }

      connectedCallback() {
        super.connectedCallback();
        // Theming contract (EXTENSION-CONTRACT.md §7): the host exposes a root part.
        this.setAttribute("part", "root");
      }

      // Snapshot of the declared state keys (actions read state, return the
      // next state — the Elixir `%{state | ...}` shape).
      __tesseraState() {
        return {#{state_snapshot_keys(spec)}};
      }

      __tesseraSetState(next) {
        for (const k of Object.keys(next)) this[k] = next[k];
      }

      // Template-bound invocations (the lowered `$click`/`$event` bindings)
      // route through the SAME action pipeline as the public dispatchAction
      // (EXTENSION-CONTRACT.md §6.4): interceptable by onAction interceptors,
      // vetoable, async-chained, and a committed transition fires
      // tsr-state-change. Errors are captured into the DispatchResult (the
      // internal invocation "catches" — the returned Promise never rejects).
      __tesseraRunAction(name, params = {}, ev = null) {
        return this.__tesseraDispatch(name, params, ev);
      }

    #{action_methods(spec)}#{lifecycle_block(spec)}

      render() {
        return #{spec.template[:render_js]};
      }
    }

    export const tag = #{inspect(tag)};
    export { #{class} };

    export function register() {
      return defineOnce(#{inspect(tag)}, #{class});
    }

    // Auto-register on direct ESM import (non-Hologram hosts). Hologram hosts
    // reach this module through the generated wrapper, whose own top-level
    // register() call is the load-bearing one — defineOnce makes both safe.
    register();
    """
  end

  # -- derived element module (EXTENSION-CONTRACT.md §5.8) ---------------------
  #
  # A fresh-tag derived element extends the BASE class (imported from the
  # base's generated element module — base artifacts untouched) re-mixed with
  # the MERGED contract, so the merged spec drives attribute coercion, event
  # registration and derived-tag behaviors. Non-overridden inherited members
  # inherit through the ES class chain (Lit finalizes up the prototype chain);
  # only new/overridden members are emitted. Overridden actions down-call via
  # real ES `super` (the base_action/3 special form lowers to it). Styles
  # compose explicitly — Lit does NOT auto-inherit styles (#82).

  defp derived_element_module(%Spec{} = spec) do
    base_spec = spec.derived_from.__tessera_spec__()
    base_class = class_name(base_spec)
    class = class_name(spec)
    tag = spec.tag
    snake = Codegen.snake_tag(spec)
    author_styles = new_entries(spec.styles)
    shared = shared_imports(%{spec | styles: author_styles})

    imports =
      [lit_import(spec)] ++
        directive_imports(spec) ++
        [
          ~s|import { defineOnce, TesseraElement, emit } from "@noizu/tessera-core";|,
          ~s|import contract from "./#{snake}.contract.generated.mjs";|,
          ~s|import { #{base_class} } from #{Spec.json_literal(base_import_path(spec, base_spec))};|
        ] ++
        Enum.map(shared, fn {binding, path} ->
          ~s|import { styles as #{binding} } from #{Spec.json_literal(path)};|
        end)

    """
    // Generated by noizu_tessera (extension derivation) — do not edit.
    // Source of truth: #{source_name(spec)}.
    // Derives from: #{source_name(base_spec)} (#{base_spec.tag}). Base artifacts are untouched.
    // Template lexer: #{spec.template[:lexer]}; subset: see docs/notes/spike-elixir-to-lit.md.
    #{Enum.join(imports, "\n")}

    // nil-safe interpolation helper (renders nothing for null/undefined).
    const __t = (v) => (v == null ? undefined : v);

    class #{class} extends TesseraElement(#{base_class}, contract, #{extension_descriptor(spec)}) {
      static properties = #{derived_properties_object(spec)};

      static styles = #{derived_styles_array(spec, shared, base_class)};

      constructor() {
        super();
    #{derived_constructor_defaults(spec)}
      }

      // Snapshot of the MERGED state keys (inherited + new) so derived actions
      // read the full state. Inherited action/setState/runAction methods ride
      // the ES class chain from #{base_class}.
      __tesseraState() {
        return {#{state_snapshot_keys(spec)}};
      }

    #{derived_action_methods(spec)}#{derived_lifecycle_block(spec)}

      render() {
        return #{spec.template[:render_js]};
      }
    }

    export const tag = #{inspect(tag)};
    export { #{class} };

    export function register() {
      return defineOnce(#{inspect(tag)}, #{class});
    }

    // Auto-register on direct ESM import (non-Hologram hosts). defineOnce makes
    // both this and the wrapper's top-level register() safe.
    register();
    """
  end

  # Entries the derived module itself declared (new or overriding). Inherited
  # entries (marked by the merge) ride the ES class chain and are not re-emitted.
  defp new_entries(entries), do: Enum.reject(entries, & &1[:inherited])

  defp base_import_path(%Spec{file: file}, %Spec{} = base_spec) when is_binary(file) do
    base_path = Path.join(Path.dirname(base_spec.file), "#{base_spec.tag}.element.generated.mjs")
    rel = Path.relative_to(base_path, Path.dirname(file))
    if String.starts_with?(rel, "."), do: rel, else: "./" <> rel
  end

  defp base_import_path(%Spec{}, %Spec{} = base_spec),
    do: "./#{base_spec.tag}.element.generated.mjs"

  defp derived_properties_object(%Spec{} = spec) do
    entries =
      Enum.map(
        Enum.map(new_entries(spec.state), &{Atom.to_string(&1.name), &1}) ++
          Enum.map(new_entries(spec.attrs), &{Naming.snake_to_camel(&1.name), &1}) ++
          Enum.map(new_entries(spec.props), &{Naming.snake_to_camel(&1.name), &1}),
        fn {key, entry} -> "#{key}: { #{property_options_js(entry)} }" end
      )

    case entries do
      [] -> "{}"
      _ -> "{\n      " <> Enum.join(entries, ",\n      ") <> ",\n    }"
    end
  end

  # `[...BaseClass.styles, …author entries]` — Lit does not auto-inherit styles,
  # so the base's composed array is spread first and the derived author's css
  # blocks / shared modules append (later entries win the cascade).
  defp derived_styles_array(%Spec{} = spec, shared, base_class) do
    bindings = Map.new(shared, fn {binding, path} -> {path, binding} end)

    entries =
      Enum.map(new_entries(spec.styles), fn
        %{kind: :css, value: css} -> "css`\n" <> Styles.escape_css_template(css) <> "\n`"
        %{kind: :shared, value: path} -> Map.fetch!(bindings, path)
      end)

    case entries do
      [] ->
        "[...#{base_class}.styles]"

      _ ->
        "[\n    ...#{base_class}.styles,\n    " <> Enum.join(entries, ",\n    ") <> ",\n  ]"
    end
  end

  # Only NEW state/attr/prop defaults — inherited defaults are set by the base
  # constructor up the chain.
  defp derived_constructor_defaults(%Spec{} = spec) do
    state_lines =
      Enum.map(new_entries(spec.state), fn s ->
        "        this.#{s.name} = #{Spec.json_literal(s[:default])};"
      end)

    attr_lines =
      Enum.map(new_entries(spec.attrs), fn a ->
        if a[:default] != nil,
          do: "        this.#{Naming.snake_to_camel(a.name)} = #{Spec.json_literal(a[:default])};",
          else: ""
      end)

    prop_lines =
      Enum.map(new_entries(spec.props), fn p ->
        if p[:default] != nil,
          do: "        this.#{Naming.snake_to_camel(p.name)} = #{Spec.json_literal(p[:default])};",
          else: ""
      end)

    (state_lines ++ attr_lines ++ prop_lines)
    |> Enum.reject(&(&1 == ""))
    |> case do
      [] -> ""
      lines -> Enum.join(lines, "\n")
    end
  end

  # Derived action methods use `let state` so a `state = base_action(…)`
  # rebinding (the down-call threading the next state) is legal JS.
  defp derived_action_methods(%Spec{} = spec) do
    Enum.map_join(new_entries(spec.actions), "\n\n      ", fn a ->
      "      __action_#{a.name}(params = {}, ev = null) {\n" <>
        "            let state = this.__tesseraState();\n" <>
        "            return #{a.js};\n" <>
        "          }"
    end)
  end

  defp derived_lifecycle_block(%Spec{} = spec) do
    methods =
      @lifecycle_order
      |> Enum.filter(fn hook ->
        entry = spec.lifecycle[hook]
        entry && !entry[:inherited]
      end)
      |> Enum.map_join("\n\n", fn hook -> lifecycle_method(hook, spec.lifecycle[hook].js) end)

    if methods == "", do: "", else: "\n\n" <> methods
  end

  @doc "Path of the generated element module under `dir`."
  @spec element_path(Spec.t(), String.t()) :: String.t()
  def element_path(%Spec{} = spec, dir), do: Path.join(dir, "#{spec.tag}.element.generated.mjs")

  @doc "Write-if-changed `element_module/1` (returns `:written | :unchanged | {:error, reason}`)."
  @spec write_element_module(Spec.t(), String.t()) :: :written | :unchanged | {:error, term()}
  def write_element_module(%Spec{} = spec, dir) do
    write_if_changed(element_path(spec, dir), element_module(spec))
  end

  # -- js entry wrapper ---------------------------------------------------------

  @doc """
  The generated `:js` entry wrapper for Hologram hosts (top-level
  `register()`, CONTRACT.md §5).
  """
  @spec wrapper_module(Spec.t()) :: String.t()
  def wrapper_module(%Spec{} = spec) do
    class = class_name(spec)

    """
    // Generated by noizu_tessera (spike/elixir-to-lit) — do not edit.
    // js_import entry: bundles the generated Lit element into Hologram page
    // bundles and registers it on load (CONTRACT.md §5).
    import { register } from "./#{spec.tag}.element.generated.mjs";

    register();

    export { register };
    export { #{class} } from "./#{spec.tag}.element.generated.mjs";
    """
  end

  @doc """
  Write the wrapper only when it does not exist (a hand-written element
  `.mjs` is never clobbered). Returns `:written | :exists | {:error, reason}`.
  """
  @spec write_wrapper_module(Spec.t(), String.t()) :: :written | :exists | {:error, term()}
  def write_wrapper_module(%Spec{} = spec, dir) do
    path = Path.join(dir, spec.js)

    if File.exists?(path) do
      :exists
    else
      case write_if_changed(path, wrapper_module(spec)) do
        {:error, reason} -> {:error, reason}
        _ -> :written
      end
    end
  end

  # -- internals ----------------------------------------------------------------

  # Directive imports (lit-parity 1d): emitted only when the directive name
  # appears in the compiled render body. Word-boundary scans of render_js are
  # deterministic and need no ctx threading; a false positive (the word in
  # escaped text) only adds an unused import, never a wrong one.
  @directive_imports [
    {"classMap", "lit/directives/class-map.js"},
    {"styleMap", "lit/directives/style-map.js"},
    {"ifDefined", "lit/directives/if-defined.js"}
  ]

  defp render_js(%Spec{template: nil}), do: ""
  defp render_js(%Spec{template: template}), do: template[:render_js] || ""

  defp lit_import(%Spec{} = spec) do
    if Regex.match?(~r/\bnothing\b/, render_js(spec)) do
      ~s|import { LitElement, html, css, nothing } from "lit";|
    else
      ~s|import { LitElement, html, css } from "lit";|
    end
  end

  defp directive_imports(%Spec{} = spec) do
    js = render_js(spec)

    for {name, path} <- @directive_imports, Regex.match?(~r/\b#{name}\b/, js) do
      ~s|import { #{name} } from "#{path}";|
    end
  end

  # Shared style modules (lit-parity row 92): one import binding per distinct
  # path, first-declaration order. The binding joins the static styles array
  # at the entry's declared position.
  defp shared_imports(%Spec{} = spec) do
    spec.styles
    |> Enum.filter(&(&1.kind == :shared))
    |> Enum.map(& &1.value)
    |> Enum.uniq()
    |> Enum.with_index()
    |> Enum.map(fn {path, i} -> {"__tsrSharedStyles#{i}", path} end)
  end

  # `static styles = [baseStyles, …author entries]` — base first, author css
  # blocks and shared-module bindings appended in declaration order (later
  # entries win the cascade). Author CSS is escaped for the css`` literal.
  defp styles_array(%Spec{} = spec, shared) do
    bindings = Map.new(shared, fn {binding, path} -> {path, binding} end)

    entries =
      Enum.map(spec.styles, fn
        %{kind: :css, value: css} -> "css`\n" <> Styles.escape_css_template(css) <> "\n`"
        %{kind: :shared, value: path} -> Map.fetch!(bindings, path)
      end)

    case entries do
      [] ->
        "[baseStyles]"

      _ ->
        "[\n    baseStyles,\n    " <> Enum.join(entries, ",\n    ") <> ",\n  ]"
    end
  end

  defp class_name(%Spec{} = spec) do
    spec.tag
    |> String.split("-")
    |> Enum.map(&String.capitalize/1)
    |> Enum.join()
  end

  # The extension descriptor passed to the TesseraElement mixin as its third
  # argument (EXTENSION-CONTRACT.md §6.1): the declared state keys (snake —
  # the compiled bodies keep Elixir names internally; the snapshot is the
  # camelCase projection), EVERY declared action name (open surface, D2 —
  # `internal:` ones included), and the `internal:` subset the runtime warns
  # on interception against (advisory, never a gate, §10), and the declared
  # extension_api (§8.3, fed to the `tesseraExtensionApi` static; defaulted to
  # 1.0.0 for specs that declare none). For a derived
  # spec this is the MERGED surface (new + inherited names ride the ES chain
  # into the same registry).
  defp extension_descriptor(%Spec{} = spec) do
    state = Enum.map(spec.state, &Atom.to_string(&1.name))
    actions = Enum.map(spec.actions, &Atom.to_string(&1.name))
    internal = spec.actions |> Enum.filter(& &1[:internal]) |> Enum.map(&Atom.to_string(&1.name))
    extension_api = spec.extension_api || Spec.default_extension_api()

    "{state: #{Spec.json_literal(state)}, actions: #{Spec.json_literal(actions)}, " <>
      "internalActions: #{Spec.json_literal(internal)}, " <>
      "extensionApi: #{Spec.json_literal(extension_api)}}"
  end

  defp source_name(%Spec{module: nil, file: file}), do: file || "Noizu.Tessera.Spec"
  defp source_name(%Spec{module: mod}), do: inspect(mod)

  defp properties_object(%Spec{} = spec) do
    entries =
      Enum.map(state_props(spec) ++ attr_props(spec) ++ prop_props(spec), fn {key, entry} ->
        "#{key}: { #{property_options_js(entry)} }"
      end)

    # A template-only component (no attrs/props/state) has no reactive
    # properties — emit a valid empty object, never "{ , }" (a SyntaxError).
    case entries do
      [] -> "{}"
      _ -> "{\n      " <> Enum.join(entries, ",\n      ") <> ",\n    }"
    end
  end

  defp state_props(%Spec{} = spec) do
    Enum.map(spec.state, fn s -> {Atom.to_string(s.name), s} end)
  end

  defp attr_props(%Spec{} = spec) do
    Enum.map(spec.attrs, fn a -> {Naming.snake_to_camel(a.name), a} end)
  end

  defp prop_props(%Spec{} = spec) do
    Enum.map(spec.props, fn p -> {Naming.snake_to_camel(p.name), p} end)
  end

  # Lit property options: type always; attribute (rename / false) and reflect
  # only when the author declared them. converter/hasChanged are pass-through
  # for a future spec that carries raw JS — NOT author-exposed in the DSL
  # (restricted subset; lit-parity 4a accepts them with an escape hatch).
  defp property_options_js(entry) do
    opts = ["type: #{lit_type(entry.type)}"]

    opts =
      case entry[:attribute] do
        nil -> opts
        false -> opts ++ ["attribute: false"]
        name when is_binary(name) -> opts ++ ["attribute: #{Spec.json_literal(name)}"]
      end

    opts = if entry[:reflect] == true, do: opts ++ ["reflect: true"], else: opts

    opts =
      if is_binary(entry[:converter]), do: opts ++ ["converter: #{entry[:converter]}"], else: opts

    opts =
      if is_binary(entry[:has_changed]),
        do: opts ++ ["hasChanged: #{entry[:has_changed]}"],
        else: opts

    Enum.join(opts, ", ")
  end

  defp lit_type(:integer), do: "Number"
  defp lit_type(:float), do: "Number"
  defp lit_type(:string), do: "String"
  defp lit_type(:boolean), do: "Boolean"
  defp lit_type(:list), do: "Array"
  defp lit_type(_), do: "Object"

  defp constructor_defaults(%Spec{} = spec) do
    state_lines =
      Enum.map(spec.state, fn s ->
        "        this.#{s.name} = #{Spec.json_literal(s[:default])};"
      end)

    attr_lines =
      Enum.map(spec.attrs, fn a ->
        if a[:default] != nil do
          "        this.#{Naming.snake_to_camel(a.name)} = #{Spec.json_literal(a[:default])};"
        else
          ""
        end
      end)

    # Prop defaults initialize here too — a standalone Lit host (no Hologram
    # feeding props) must see the declared default before the first render.
    prop_lines =
      Enum.map(spec.props, fn p ->
        if p[:default] != nil do
          "        this.#{Naming.snake_to_camel(p.name)} = #{Spec.json_literal(p[:default])};"
        else
          ""
        end
      end)

    (state_lines ++ attr_lines ++ prop_lines)
    |> Enum.reject(&(&1 == ""))
    |> case do
      [] -> ""
      lines -> Enum.join(lines, "\n")
    end
  end

  defp state_snapshot_keys(%Spec{} = spec) do
    spec.state
    |> Enum.map_join(", ", &"#{&1.name}: this.#{&1.name}")
    |> case do
      "" -> ""
      s -> " " <> s <> " "
    end
  end

  defp action_methods(%Spec{} = spec) do
    Enum.map_join(spec.actions, "\n\n      ", fn a ->
      "      __action_#{a.name}(params = {}, ev = null) {\n" <>
        "            const state = this.__tesseraState();\n" <>
        "            return #{a.js};\n" <>
        "          }"
    end)
  end

  # -- lifecycle lowering (lit-parity 1c) --------------------------------------
  #
  # Only declared hooks emit methods. `changed` is a plain-object snapshot of
  # Lit's changedProperties Map (Object.fromEntries) — keys are property names
  # (camelCase attrs/props, snake state), values are the OLD values; it is NOT
  # a live Map. shouldUpdate returns the hook value (false freezes the update);
  # willUpdate applies an object result as next state; firstUpdated/updated
  # evaluate for side effects (emit) and discard the result.

  defp lifecycle_block(%Spec{lifecycle: lifecycle}) when lifecycle == %{}, do: ""

  defp lifecycle_block(%Spec{} = spec) do
    methods =
      @lifecycle_order
      |> Enum.filter(&Map.has_key?(spec.lifecycle, &1))
      |> Enum.map_join("\n\n", fn hook -> lifecycle_method(hook, spec.lifecycle[hook].js) end)

    "\n\n" <> methods
  end

  defp lifecycle_method(:should_update, js) do
    "      shouldUpdate(changedProperties) {\n" <>
      "            const state = this.__tesseraState();\n" <>
      "            const changed = Object.fromEntries(changedProperties);\n" <>
      "            return #{js};\n" <>
      "          }"
  end

  defp lifecycle_method(:will_update, js) do
    "      willUpdate(changedProperties) {\n" <>
      "            const state = this.__tesseraState();\n" <>
      "            const changed = Object.fromEntries(changedProperties);\n" <>
      "            const next = #{js};\n" <>
      "            if (next != null && typeof next === \"object\") this.__tesseraSetState(next);\n" <>
      "          }"
  end

  defp lifecycle_method(hook, js) when hook in [:first_updated, :updated] do
    name = if hook == :first_updated, do: "firstUpdated", else: "updated"

    "      #{name}(changedProperties) {\n" <>
      "            const state = this.__tesseraState();\n" <>
      "            const changed = Object.fromEntries(changedProperties);\n" <>
      "            // side-effects only (emit) — the hook's return value is discarded\n" <>
      "            const next = #{js};\n" <>
      "          }"
  end

  defp write_if_changed(path, content) do
    case File.read(path) do
      {:ok, ^content} ->
        :unchanged

      _ ->
        dir = Path.dirname(path)

        with :ok <- File.mkdir_p(dir) do
          case File.write(path, content) do
            :ok -> :written
            {:error, reason} -> {:error, reason}
          end
        else
          {:error, reason} -> {:error, reason}
        end
    end
  end
end
