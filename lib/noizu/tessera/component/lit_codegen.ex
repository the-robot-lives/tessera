defmodule Noizu.Tessera.Component.LitCodegen do
  @moduledoc """
  SPIKE (`spike/elixir-to-lit`): emits the Lit element module for a spec that
  declared `state` / `template ~TSR` / `action` (docs/notes/spike-elixir-to-lit.md
  §codegen).

  Output (colocated with the component's `.ex`):

    * `<tag>.element.generated.mjs` — a `LitElement` subclass mixed with
      `TesseraElement` (CONTRACT.md §4): reactive properties from state +
      attrs + props, a `render()` built from the template, one method per
      action (running the JS translated at compile time), `emit` routed
      through `@noizu/tessera-core`'s `emit` (so the `data-tsr-on` Hologram
      bridge keeps working), and an exported `register()`.
    * `<snake>.mjs` — the `:js` entry wrapper (`register();` top-level —
      load-bearing for Hologram page bundles, CONTRACT.md §5). Written only
      when it does not exist, so a hand-written element `.mjs` is never
      clobbered.

  Deterministic: same spec in, same bytes out (golden fixtures pin it).
  """

  alias Noizu.Tessera.Codegen
  alias Noizu.Tessera.Naming
  alias Noizu.Tessera.Spec

  # -- element module ----------------------------------------------------------

  @doc "The `<tag>.element.generated.mjs` text for a template-bearing spec."
  @spec element_module(Spec.t()) :: String.t()
  def element_module(%Spec{} = spec) do
    class = class_name(spec)
    tag = spec.tag
    snake = Codegen.snake_tag(spec)

    """
    // Generated by noizu_tessera (spike/elixir-to-lit) — do not edit.
    // Source of truth: #{source_name(spec)}.
    // Template lexer: #{spec.template[:lexer]}; subset: see docs/notes/spike-elixir-to-lit.md.
    import { LitElement, html, css } from "lit";
    import { defineOnce, TesseraElement, emit } from "@noizu/tessera-core";
    import contract from "./#{snake}.contract.generated.mjs";

    // nil-safe interpolation helper (renders nothing for null/undefined).
    const __t = (v) => (v == null ? undefined : v);

    class #{class} extends TesseraElement(LitElement, contract) {
      static properties = #{properties_object(spec)};

      static styles = css`
      :host {
        display: block;
        font-family: system-ui, -apple-system, sans-serif;
      }
      `;

      constructor() {
        super();
    #{constructor_defaults(spec)}
      }

      // Snapshot of the declared state keys (actions read state, return the
      // next state — the Elixir `%{state | ...}` shape).
      __tesseraState() {
        return {#{state_snapshot_keys(spec)}};
      }

      __tesseraSetState(next) {
        for (const k of Object.keys(next)) this[k] = next[k];
      }

      __tesseraRunAction(name, params = {}, ev = null) {
        const handler = this[`__action_${name}`];
        if (typeof handler !== "function") {
          console.warn(`[tessera] <#{tag}> has no action "${name}"`);
          return;
        }
        const next = handler.call(this, params, ev);
        if (next != null && typeof next === "object") this.__tesseraSetState(next);
      }

    #{action_methods(spec)}

      render() {
        return #{spec.template[:render_js]};
      }
    }

    export const tag = #{inspect(tag)};
    export { #{class} };

    export function register() {
      return defineOnce(#{inspect(tag)}, #{class});
    }

    // Auto-register on direct ESM import (non-Hologram hosts). Hologram hosts
    // reach this module through the generated wrapper, whose own top-level
    // register() call is the load-bearing one — defineOnce makes both safe.
    register();
    """
  end

  @doc "Path of the generated element module under `dir`."
  @spec element_path(Spec.t(), String.t()) :: String.t()
  def element_path(%Spec{} = spec, dir), do: Path.join(dir, "#{spec.tag}.element.generated.mjs")

  @doc "Write-if-changed `element_module/1` (returns `:written | :unchanged | {:error, reason}`)."
  @spec write_element_module(Spec.t(), String.t()) :: :written | :unchanged | {:error, term()}
  def write_element_module(%Spec{} = spec, dir) do
    write_if_changed(element_path(spec, dir), element_module(spec))
  end

  # -- js entry wrapper ---------------------------------------------------------

  @doc """
  The generated `:js` entry wrapper for Hologram hosts (top-level
  `register()`, CONTRACT.md §5).
  """
  @spec wrapper_module(Spec.t()) :: String.t()
  def wrapper_module(%Spec{} = spec) do
    class = class_name(spec)

    """
    // Generated by noizu_tessera (spike/elixir-to-lit) — do not edit.
    // js_import entry: bundles the generated Lit element into Hologram page
    // bundles and registers it on load (CONTRACT.md §5).
    import { register } from "./#{spec.tag}.element.generated.mjs";

    register();

    export { register };
    export { #{class} } from "./#{spec.tag}.element.generated.mjs";
    """
  end

  @doc """
  Write the wrapper only when it does not exist (a hand-written element
  `.mjs` is never clobbered). Returns `:written | :exists | {:error, reason}`.
  """
  @spec write_wrapper_module(Spec.t(), String.t()) :: :written | :exists | {:error, term()}
  def write_wrapper_module(%Spec{} = spec, dir) do
    path = Path.join(dir, spec.js)

    if File.exists?(path) do
      :exists
    else
      case write_if_changed(path, wrapper_module(spec)) do
        {:error, reason} -> {:error, reason}
        _ -> :written
      end
    end
  end

  # -- internals ----------------------------------------------------------------

  defp class_name(%Spec{} = spec) do
    spec.tag
    |> String.split("-")
    |> Enum.map(&String.capitalize/1)
    |> Enum.join()
  end

  defp source_name(%Spec{module: nil, file: file}), do: file || "Noizu.Tessera.Spec"
  defp source_name(%Spec{module: mod}), do: inspect(mod)

  defp properties_object(%Spec{} = spec) do
    entries =
      Enum.map(state_props(spec) ++ attr_props(spec) ++ prop_props(spec), fn {key, type} ->
        "#{key}: { type: #{lit_type(type)} }"
      end)

    "{\n      " <> Enum.join(entries, ",\n      ") <> ",\n    }"
  end

  defp state_props(%Spec{} = spec) do
    Enum.map(spec.state, fn s -> {Atom.to_string(s.name), s.type} end)
  end

  defp attr_props(%Spec{} = spec) do
    Enum.map(spec.attrs, fn a -> {Naming.snake_to_camel(a.name), a.type} end)
  end

  defp prop_props(%Spec{} = spec) do
    Enum.map(spec.props, fn p -> {Naming.snake_to_camel(p.name), p.type} end)
  end

  defp lit_type(:integer), do: "Number"
  defp lit_type(:float), do: "Number"
  defp lit_type(:string), do: "String"
  defp lit_type(:boolean), do: "Boolean"
  defp lit_type(_), do: "Object"

  defp constructor_defaults(%Spec{} = spec) do
    state_lines =
      Enum.map(spec.state, fn s ->
        "        this.#{s.name} = #{Spec.json_literal(s[:default])};"
      end)

    attr_lines =
      Enum.map(spec.attrs, fn a ->
        if a[:default] != nil do
          "        this.#{Naming.snake_to_camel(a.name)} = #{Spec.json_literal(a[:default])};"
        else
          ""
        end
      end)

    (state_lines ++ Enum.reject(attr_lines, &(&1 == "")))
    |> Enum.reject(&(&1 == ""))
    |> case do
      [] -> ""
      lines -> Enum.join(lines, "\n")
    end
  end

  defp state_snapshot_keys(%Spec{} = spec) do
    spec.state
    |> Enum.map_join(", ", &"#{&1.name}: this.#{&1.name}")
    |> case do
      "" -> ""
      s -> " " <> s <> " "
    end
  end

  defp action_methods(%Spec{} = spec) do
    Enum.map_join(spec.actions, "\n\n      ", fn a ->
      "      __action_#{a.name}(params = {}, ev = null) {\n" <>
        "            const state = this.__tesseraState();\n" <>
        "            return #{a.js};\n" <>
        "          }"
    end)
  end

  defp write_if_changed(path, content) do
    case File.read(path) do
      {:ok, ^content} ->
        :unchanged

      _ ->
        dir = Path.dirname(path)

        with :ok <- File.mkdir_p(dir) do
          case File.write(path, content) do
            :ok -> :written
            {:error, reason} -> {:error, reason}
          end
        else
          {:error, reason} -> {:error, reason}
        end
    end
  end
end
