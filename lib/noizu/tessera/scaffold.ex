defmodule Noizu.Tessera.Scaffold do
  @moduledoc false

  # Content builders behind `mix tessera.gen.component`. Pure functions of
  # their arguments (the Mix task only parses args and writes files) so they
  # are unit-testable without a Mix project context. The scaffolded `.mjs` is
  # a TEMPLATE only — the JS core itself lives in `priv/js/` (@noizu/tessera-core).

  alias Noizu.Tessera.Spec

  @doc "`persona-card` → `\"PersonaCard\"` (used as the default module suffix)."
  @spec camelize_tag(String.t()) :: String.t()
  def camelize_tag(tag) do
    tag
    |> String.split("-")
    |> Enum.map(&String.capitalize/1)
    |> Enum.join("")
  end

  @doc "Default module name for a host app: `<AppCamel>.Components.<CamelTag>`."
  @spec default_module(String.t(), String.t()) :: String.t()
  def default_module(app_name, tag) do
    app_camel =
      app_name
      |> to_string()
      |> String.split("_")
      |> Enum.map(&String.capitalize/1)
      |> Enum.join("")

    Enum.join([app_camel, "Components", camelize_tag(tag)], ".")
  end

  @doc "The scaffolded spec module content."
  @spec spec_module_content(String.t(), String.t()) :: String.t()
  def spec_module_content(tag, module_name) do
    snake = String.replace(tag, "-", "_")

    # ~s''' so the scaffold's own """ (its moduledoc) does not terminate the
    # outer heredoc.
    ~s'''
    defmodule #{module_name} do
      @moduledoc """
      `<tag>` — tessera web component spec.

      The DSL below is the contract source of truth. `mix compile` regenerates
      `#{snake}.contract.generated.mjs` next to `#{snake}.mjs` and (in Hologram
      apps) the render + bridge wiring in this module. See the tessera
      `docs/AUTHORING.md`.
      """

      use Noizu.Tessera.Component, tag: "#{tag}", js: "#{snake}.mjs"

      # DOM attribute (snake_case atom; reaches the DOM kebab-cased).
      attr :label, :string, required: true

      # JSON prop (camelCased DOM property, shipped through tsr-props).
      prop :items, :list, json: true, default: []

      # CustomEvent emitted by the element; the Hologram binding prop is
      # on_#{String.replace(tag, "-", "_")}_changed (action :#{String.replace(tag, "-", "_")}_changed
      # targets @page; {:#{String.replace(tag, "-", "_")}_changed, target: "layout" | cid} targets elsewhere).
      event "#{tag}-changed", detail: %{value: :string}

      slot "default"
      cy "#{tag}-root"
    end
    '''
  end

  @doc "The scaffolded colocated `.mjs` — a template, not an implementation."
  @spec mjs_content(String.t()) :: String.t()
  def mjs_content(tag) do
    camel = camelize_tag(tag)
    snake = String.replace(tag, "-", "_")

    """
    // #{tag} — tessera web component (scaffold).
    //
    // The generated wire contract (./#{snake}.contract.generated.mjs) is
    // regenerated by `mix compile` from the spec module. Replace this
    // template body with the real element; keep the `register` export — the
    // Hologram adapter binds it by name (CONTRACT.md §5).
    import { defineOnce, TesseraElement } from "@noizu/tessera-core";
    import contract from "./#{snake}.contract.generated.mjs";

    class #{camel} extends TesseraElement(HTMLElement, contract) {
      // Element behavior goes here. When the host provides Lit as a peer,
      // extend TesseraElement(LitElement, contract) instead to get reactive
      // rendering; with plain HTMLElement, override connectedCallback and
      // render into a shadow root yourself.
    }

    export function register() {
      return defineOnce("#{tag}", #{camel});
    }

    // Page bundles carry their own copy of this module — defineOnce makes the
    // re-execution safe (CONTRACT.md §4).
    register();
    """
  end

  @doc "The scaffolded web-test-runner test skeleton."
  @spec test_content(String.t(), String.t()) :: String.t()
  def test_content(tag, mjs_relpath_from_test) do
    camel = camelize_tag(tag)

    """
    // Scaffolded WTR test for <#{tag}> — skeleton to expand. The tessera repo
    // runs the JS suites with @web/test-runner; hosts wire their own runner
    // around assets/node_modules (see docs/CONSUMING.md).
    import { defineOnce } from "@noizu/tessera-core";
    import { #{camel} } from "#{mjs_relpath_from_test}";

    describe("#{tag}", () => {
      it("defines the custom element exactly once", () => {
        const ctor = registerTag();
        expect(customElements.get("#{tag}")).to.equal(ctor);
        // Second defineOnce call must warn-and-keep, never throw:
        expect(defineOnce("#{tag}", #{camel})).to.equal(ctor);
      });
    });

    function registerTag() {
      return defineOnce("#{tag}", #{camel});
    }
    """
  end

  @doc """
  Builds all scaffold file contents for `tag` under host project `root`.
  Returns a list of `{absolute_path, content}` — the caller writes them.
  Raises `CompileError` when `tag` violates the contract grammar.
  """
  @spec generate(String.t(), String.t(), String.t()) :: [{String.t(), String.t()}]
  def generate(tag, module_name, root) do
    Spec.validate!(:tag, tag, %{}, "mix tessera.gen.component", 0)

    snake = String.replace(tag, "-", "_")
    module_parts = String.split(module_name, ".")
    lib_relpath = Enum.map_join(module_parts, "/", &Macro.underscore/1)

    lib_path = Path.join(root, lib_relpath <> ".ex")
    mjs_path = Path.join(Path.dirname(lib_path), snake <> ".mjs")
    test_path = Path.join([root, "test", "components", snake <> "_test.mjs"])

    # test/components/<snake>_test.mjs → lib/.../<snake>.mjs
    mjs_relpath_from_test =
      Path.relative_to(mjs_path, Path.join([root, "test", "components"]))
      |> then(fn rel -> "../" <> rel end)

    [
      {lib_path, spec_module_content(tag, module_name)},
      {mjs_path, mjs_content(tag)},
      {test_path, test_content(tag, mjs_relpath_from_test)}
    ]
  end
end
